// Generate from the migrated local PostgreSQL catalog, with no remote credentials.
import { mkdir, writeFile } from "node:fs/promises";
import { createDatabase, root } from "./local-db.mjs";

const db = await createDatabase();
try {
  const { rows: columns } = await db.query(`
    select c.table_name, c.column_name, c.is_nullable, c.column_default, c.is_generated,
      c.udt_name, c.data_type, t.table_type
    from information_schema.columns c join information_schema.tables t
      on t.table_schema=c.table_schema and t.table_name=c.table_name
    where c.table_schema='public' order by c.table_name,c.ordinal_position`);
  const { rows: enums } = await db.query(`
    select t.typname, e.enumlabel from pg_type t join pg_enum e on e.enumtypid=t.oid
    join pg_namespace n on n.oid=t.typnamespace where n.nspname='public'
    order by t.typname,e.enumsortorder`);
  const { rows: relationships } = await db.query(`
    select c.conname, child.relname as table_name, parent.relname as referenced_relation,
      array_agg(ca.attname order by k.ord) as columns,
      array_agg(pa.attname order by k.ord) as referenced_columns,
      exists(select 1 from pg_constraint u where u.conrelid=c.conrelid and u.contype in ('p','u') and u.conkey=c.conkey) as one_to_one
    from pg_constraint c join pg_class child on child.oid=c.conrelid
    join pg_class parent on parent.oid=c.confrelid
    join pg_namespace n on n.oid=child.relnamespace
    cross join lateral unnest(c.conkey,c.confkey) with ordinality k(child_num,parent_num,ord)
    join pg_attribute ca on ca.attrelid=child.oid and ca.attnum=k.child_num
    join pg_attribute pa on pa.attrelid=parent.oid and pa.attnum=k.parent_num
    where c.contype='f' and n.nspname='public'
    group by c.oid,c.conname,child.relname,parent.relname order by c.conname`);
  const enumNames = new Set(enums.map((x) => x.typname));
  function type(c) {
    let t;
    if (enumNames.has(c.udt_name)) t = `Database['public']['Enums']['${c.udt_name}']`;
    else if (c.data_type === "ARRAY") t = "string[]";
    else if (c.udt_name === "jsonb" || c.udt_name === "json") t = "Json";
    else if (["int2", "int4", "int8", "numeric", "float4", "float8"].includes(c.udt_name))
      t = "number";
    else if (c.udt_name === "bool") t = "boolean";
    else t = "string";
    return t + (c.is_nullable === "YES" ? " | null" : "");
  }
  const lines = [
    "// Generated by node scripts/db/generate-types.mjs from the migrated PostgreSQL catalog.",
    "// Do not edit src/integrations/supabase/types.ts; Lovable owns that file.",
    "export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[]",
    "export type Database = {",
    "  public: {",
    "    Tables: {",
  ];
  function definition(table, view) {
    const fields = columns.filter((x) => x.table_name === table);
    lines.push(`      ${table}: {`, "        Row: {");
    for (const c of fields) lines.push(`          ${c.column_name}: ${type(c)}`);
    lines.push("        }");
    if (!view) {
      for (const operation of ["Insert", "Update"]) {
        lines.push(`        ${operation}: {`);
        for (const c of fields) {
          const generated = c.is_generated === "ALWAYS";
          const optional =
            operation === "Update" ||
            generated ||
            c.column_default !== null ||
            c.is_nullable === "YES";
          lines.push(
            `          ${c.column_name}${optional ? "?" : ""}: ${generated ? "never" : type(c)}`,
          );
        }
        lines.push("        }");
      }
    }
    lines.push("        Relationships: [");
    for (const r of relationships.filter((x) => x.table_name === table)) {
      lines.push(
        "          {",
        `            foreignKeyName: ${JSON.stringify(r.conname)}`,
        `            columns: ${JSON.stringify(r.columns)}`,
        `            isOneToOne: ${r.one_to_one}`,
        `            referencedRelation: ${JSON.stringify(r.referenced_relation)}`,
        `            referencedColumns: ${JSON.stringify(r.referenced_columns)}`,
        "          },",
      );
    }
    lines.push("        ]", "      }");
  }
  for (const table of new Set(
    columns.filter((x) => x.table_type === "BASE TABLE").map((x) => x.table_name),
  ))
    definition(table, false);
  lines.push("    }", "    Views: {");
  for (const table of new Set(
    columns.filter((x) => x.table_type === "VIEW").map((x) => x.table_name),
  ))
    definition(table, true);
  lines.push(
    "    }",
    "    Functions: {",
    "      current_role: { Args: Record<PropertyKey, never>; Returns: Database['public']['Enums']['app_role'] | null }",
    "      next_quote_code: { Args: { p_sku: string; p_language: string }; Returns: string }",
    "    }",
    "    Enums: {",
  );
  for (const name of enumNames)
    lines.push(
      `      ${name}: ${enums
        .filter((x) => x.typname === name)
        .map((x) => JSON.stringify(x.enumlabel))
        .join(" | ")}`,
    );
  lines.push(
    "    }",
    "    CompositeTypes: Record<never, never>",
    "  }",
    "}",
    "export type Tables<T extends keyof Database['public']['Tables']> = Database['public']['Tables'][T]['Row']",
    "export type TablesInsert<T extends keyof Database['public']['Tables']> = Database['public']['Tables'][T]['Insert']",
    "export type TablesUpdate<T extends keyof Database['public']['Tables']> = Database['public']['Tables'][T]['Update']",
    "export type Enums<T extends keyof Database['public']['Enums']> = Database['public']['Enums'][T]",
    "",
  );
  await mkdir(new URL("src/types/", root), { recursive: true });
  // Keep the generated file stable and compliant with the repository formatter.
  const { format } = await import("prettier");
  await writeFile(
    new URL("src/types/db.ts", root),
    await format(lines.join("\n"), {
      parser: "typescript",
      printWidth: 100,
      semi: true,
      singleQuote: false,
      trailingComma: "all",
    }),
  );
  console.log("Generated src/types/db.ts from all tables, views, enums and foreign keys");
} finally {
  await db.close();
}
